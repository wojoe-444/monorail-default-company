#!/usr/bin/env node
/**
 * Diff-aware helper for posting native GitHub PR inline `suggestion` review comments.
 *
 * GitHub's `pulls.createReview` API rejects review comments whose `line` or
 * `start_line` fall outside the PR's unified diff hunks (HTTP 422). This module
 * parses each PR file's `patch` to compute the exact set of valid RIGHT-side
 * line numbers and partitions suggestions into:
 *   - `inlineComments`: ready to pass directly to `pulls.createReview({ comments })`
 *   - `outOfDiff`: suggestions touching unchanged lines (rendered cleanly in the review body)
 */

'use strict'

const HUNK_RE = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/

/**
 * Parse a GitHub unified diff `patch` string and return a Set of valid
 * 1-based RIGHT-side line numbers that GitHub accepts for inline review comments.
 */
function parseDiffRightLines(patch) {
  const validLines = new Set()
  if (!patch) return validLines

  let rightLine = 0
  let inHunk = false

  for (const rawLine of String(patch).split('\n')) {
    const hunkMatch = rawLine.match(HUNK_RE)
    if (hunkMatch) {
      rightLine = Number.parseInt(hunkMatch[1], 10)
      inHunk = true
      continue
    }
    if (!inHunk) continue

    if (rawLine.startsWith('+')) {
      validLines.add(rightLine)
      rightLine += 1
    } else if (rawLine.startsWith(' ')) {
      validLines.add(rightLine)
      rightLine += 1
    } else if (rawLine.startsWith('-')) {
      // Deletion exists only on LEFT side; rightLine does not advance.
    } else if (rawLine.startsWith('\\')) {
      // "\ No newline at end of file" marker; no line advance.
    }
  }
  return validLines
}

/**
 * Partition SQLFluff suggestion objects against the PR's `pulls.listFiles` array.
 */
function partitionSuggestions(suggestions, prFiles, { maxInline = 25 } = {}) {
  const fileDiffLines = new Map()
  for (const f of prFiles || []) {
    if (f.filename) {
      fileDiffLines.set(f.filename, parseDiffRightLines(f.patch))
    }
  }

  const inlineComments = []
  const outOfDiff = []

  for (const s of suggestions || []) {
    const valid = fileDiffLines.get(s.path)
    const startLine = Number(s.start_line || s.line)
    const endLine = Number(s.line)

    let allInDiff = Boolean(valid && valid.size > 0 && startLine <= endLine)
    if (allInDiff) {
      for (let ln = startLine; ln <= endLine; ln++) {
        if (!valid.has(ln)) {
          allInDiff = false
          break
        }
      }
    }

    if (allInDiff && inlineComments.length < maxInline) {
      const comment = {
        path: s.path,
        line: endLine,
        side: 'RIGHT',
        body: s.body,
      }
      if (startLine < endLine) {
        comment.start_line = startLine
        comment.start_side = 'RIGHT'
      }
      inlineComments.push(comment)
    } else {
      outOfDiff.push(s)
    }
  }

  return { inlineComments, outOfDiff }
}

function buildReviewBody({ inlineComments, outOfDiff, modeLabel = 'SQLFluff Advisory Quick-Fixes' }) {
  const lines = [`### 💡 ${modeLabel}`, '']

  if (inlineComments.length > 0) {
    lines.push(
      '> [!TIP]',
      `> Posted **${inlineComments.length}** one-click inline \`suggestion\` comment(s) directly on your diff. Open the **Files changed** tab and click **Commit suggestion** (or **Add suggestion to batch**) on any items you want to apply!`,
      ''
    )
  } else {
    lines.push(
      '> [!NOTE]',
      '> No fixable suggestions fell inside the lines touched by this PR diff.',
      ''
    )
  }

  if (outOfDiff.length > 0) {
    lines.push(
      `<details><summary>📌 ${outOfDiff.length} additional suggestion(s) on untouched lines outside the PR diff</summary>`,
      '',
      'GitHub only allows inline `suggestion` buttons on lines within the PR diff hunk. These apply to untouched context lines:',
      ''
    )
    for (const s of outOfDiff.slice(0, 15)) {
      const loc = s.start_line && s.start_line !== s.line ? `L${s.start_line}-L${s.line}` : `L${s.line}`
      const rules = (s.rule_codes || []).map((r) => `\`${r}\``).join(', ')
      lines.push(`- **\`${s.path}\` (${loc})** — ${rules}`)
    }
    if (outOfDiff.length > 15) {
      lines.push(`- *…and ${outOfDiff.length - 15} more*`)
    }
    lines.push('', '</details>', '')
  }

  lines.push('<sub>Generated by `scripts/lint-sqlx.py` & `scripts/post-pr-suggestions.cjs`</sub>')
  return lines.join('\n')
}

module.exports = {
  parseDiffRightLines,
  partitionSuggestions,
  buildReviewBody,
}
